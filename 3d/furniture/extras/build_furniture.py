#!/usr/bin/env python3
"""Regenerate extras/furniture.html (hall 11 + the laundry niche; the <script type="module"> block that
gen3d.py splices in at <!--__FURNITURE__-->) from furniture.json + the GLB files in models/.

Same pattern as bedroom4/build_furniture.py: each GLB is embedded once as base64 (the page runs from
file://, so fetch() is blocked) and parsed with GLTFLoader + DRACOLoader; its bounding box is compared
with the product-page dimensions and the model is scaled only when it is off by more than TOL.

Extra piece fields used here:
  wall: true     wall-mounted: x, y is the point on the wall face, the model's back sits on it,
                 "lift" = height of its lowest point above the floor
  tilt_deg       rotate the model about its own x axis first (IKEA mirrors are modelled lying flat)
  kind           drawn from code (no IKEA model): "mirror_glass", "dryer", "coat"
  parent/local   placed in the parent's frame: [x across, height above the parent's bottom, z towards its front]

Usage:  python3 build_furniture.py            (writes furniture.html next to this file)
"""
import base64, json, struct, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOL = 0.08
DRACO = 'https://cdn.jsdelivr.net/npm/three@0.183.0/examples/jsm/libs/draco/gltf/'
KEEP = ('id', 'product', 'rot_deg', 'x', 'y', 'lift', 'parent', 'local', 'kind', 'dims_mm', 'colors', 'wall', 'tilt_deg', 'color', 'lean_deg')


def glb_bbox(path):
    """Axis-aligned bbox (x, y, z sizes, metres) from POSITION accessor min/max + node translations."""
    b = path.read_bytes()
    n = struct.unpack('<I', b[12:16])[0]
    j = json.loads(b[20:20 + n])
    lo, hi = [1e9] * 3, [-1e9] * 3
    for node in j.get('nodes', []):
        if 'mesh' not in node:
            continue
        t = node.get('translation', [0, 0, 0])
        for prim in j['meshes'][node['mesh']]['primitives']:
            a = j['accessors'][prim['attributes']['POSITION']]
            lo = [min(l, m + o) for l, m, o in zip(lo, a['min'], t)]
            hi = [max(h, m + o) for h, m, o in zip(hi, a['max'], t)]
    return [h - l for l, h in zip(lo, hi)]


def main():
    spec = json.loads((HERE / 'furniture.json').read_text())
    pieces, models, ok = [], {}, True
    for p in spec['pieces']:
        keep = {k: p[k] for k in KEEP if k in p}
        if 'model' not in p:                              # drawn from code: nothing to check
            pieces.append(keep)
            continue
        path = HERE / 'models' / p['model']
        sx, sy, sz = glb_bbox(path)                       # glTF: x = width, y = height, z = depth
        if abs(p.get('tilt_deg', 0)) == 90:               # modelled lying flat: y <-> z
            sy, sz = sz, sy
        d = p['dims_mm']
        ratios = [sx / (d['w'] / 1000), sz / (d['d'] / 1000), sy / (d['h'] / 1000)]
        bad = any(abs(r - 1) > TOL for r in ratios)
        scale = 1.0
        if bad:                                           # uniform scale by the median ratio
            scale = 1 / sorted(ratios)[1]
            ok = False
        print(f"{p['id']:16s} model {sx:.3f} x {sz:.3f} x {sy:.3f} m  vs page "
              f"{d['w']/1000:.3f} x {d['d']/1000:.3f} x {d['h']/1000:.3f}  "
              f"ratios {', '.join(f'{r:.2f}' for r in ratios)}  scale {scale:.3f}", file=sys.stderr)
        if p['model'] not in models:
            models[p['model']] = base64.b64encode(path.read_bytes()).decode('ascii')
        pieces.append(keep | {'model': p['model'], 'scale': scale})

    js_models = ',\n'.join(f'  {json.dumps(k)}: "{v}"' for k, v in models.items())
    html = (HEAD.replace('__PIECES__', json.dumps(pieces, ensure_ascii=False))
                .replace('__MODELS__', js_models).replace('__DRACO__', DRACO))
    out = HERE / 'furniture.html'
    out.write_text(html)
    print(f'wrote {out} ({out.stat().st_size / 1e6:.2f} MB), {len(pieces)} pieces, {len(models)} models'
          + ('' if ok else '  (some models were rescaled)'), file=sys.stderr)


