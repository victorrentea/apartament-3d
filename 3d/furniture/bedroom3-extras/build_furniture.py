#!/usr/bin/env python3
"""Regenerate bedroom3-extras/furniture.html: the gaming setup on the MICKE desk, the painting above the
bed and the hanging plants of room 3. gen3d.py splices every furniture/*/furniture.html into the page.

furniture.json lists the pieces; block.js is the page code (drawn-from-code pieces + placement), with the
piece list and the base64 IKEA GLBs (private use only, never publish) substituted in by this script.

Usage:  python3 build_furniture.py
"""
import base64, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
KEEP = ('id', 'product', 'kind', 'model', 'x', 'y', 'h', 'on_desk', 'rot_deg', 'orient', 'flip', 'hook_h', 'sink', 'upside_down', 'dims_mm')


def main():
    spec = json.loads((HERE / 'furniture.json').read_text())
    pieces = [{k: p[k] for k in KEEP if k in p} for p in spec['pieces']]
    models = {}
    for p in pieces:
        if 'model' in p and p['model'] not in models:
            models[p['model']] = base64.b64encode((HERE / 'models' / p['model']).read_bytes()).decode('ascii')
    js = (HERE / 'block.js').read_text()
    js = js.replace('/*__PIECES__*/', json.dumps(pieces, ensure_ascii=False))
    js = js.replace('/*__MODELS__*/', ',\n'.join(f'  {json.dumps(k)}: "{v}"' for k, v in models.items()))
    html = ('<!-- bedroom3-extras: generated by 3d/furniture/bedroom3-extras/build_furniture.py from furniture.json + block.js, do not edit -->\n'
            '<script type="module">\n' + js + '\n</script>\n')
    out = HERE / 'furniture.html'
    out.write_text(html)
    print(f'wrote {out} ({out.stat().st_size / 1e6:.2f} MB), {len(pieces)} pieces, {len(models)} models', file=sys.stderr)


if __name__ == '__main__':
    main()
