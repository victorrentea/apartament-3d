#!/usr/bin/env python3
"""Regenerate furniture.html for DECOR pieces (group 'furniture-decor'): the <script type="module"> block
that gen3d.py splices in at <!--__FURNITURE__--> (it globs 3d/furniture/*/furniture.html).

Reads furniture.json + the IKEA GLBs in models/ (private use only, never publish) and the page code
in decor.js. A piece with "led" glows: emissive body, a soft halo painted on the wall, a PointLight.

Usage:  python3 build_decor.py
"""
import base64, json, struct, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DRACO = 'https://cdn.jsdelivr.net/npm/three@0.183.0/examples/jsm/libs/draco/gltf/'


def glb_bbox(path):
    b = path.read_bytes()
    n = struct.unpack('<I', b[12:16])[0]
    j = json.loads(b[20:20 + n])
    lo, hi = [1e9] * 3, [-1e9] * 3
    for node in j.get('nodes', []):
        if 'mesh' not in node:
            continue
        t = node.get('translation', [0, 0, 0])
        for prim in j['meshes'][node['mesh']]['primitives']:
            a = j['accessors'][prim['attributes']['POSITION']]
            lo = [min(l, m + o) for l, m, o in zip(lo, a['min'], t)]
            hi = [max(h, m + o) for h, m, o in zip(hi, a['max'], t)]
    return [h - l for l, h in zip(lo, hi)]


def main():
    spec = json.loads((HERE / 'furniture.json').read_text())
    pieces, models = [], {}
    for p in spec['pieces']:
        path = HERE / 'models' / p['model']
        sx, sy, sz = glb_bbox(path)
        print(f"{p['id']:12s} model bbox {sx:.3f} x {sy:.3f} x {sz:.3f} m (x, y, z), page {p['dims_mm']}", file=sys.stderr)
        models.setdefault(p['model'], base64.b64encode(path.read_bytes()).decode('ascii'))
        pieces.append({k: p[k] for k in ('id', 'product', 'model', 'x', 'y', 'h', 'rot_deg', 'led') if k in p}
                      | {'scale': p.get('scale', 1.0), 'wall': p.get('orient') == 'wall'})
    js_models = '{\n' + ',\n'.join(f'  {json.dumps(k)}: "{v}"' for k, v in models.items()) + '\n}'
    js = (HERE / 'decor.js').read_text()
    js = js.replace('__PIECES__', json.dumps(pieces, ensure_ascii=False)).replace('__MODELS__', js_models).replace('__DRACO__', DRACO)
    out = HERE / 'furniture.html'
    out.write_text('<!-- decor: generated by 3d/furniture/decor/build_decor.py from furniture.json + decor.js, do not edit -->\n'
                   '<script type="module">\n' + js + '</script>\n')
    print(f'wrote {out} ({out.stat().st_size / 1e6:.2f} MB), {len(pieces)} pieces', file=sys.stderr)


if __name__ == '__main__':
    main()
