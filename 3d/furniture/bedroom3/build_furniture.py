#!/usr/bin/env python3
"""Regenerate bedroom3/furniture.html (room 3, the second bedroom) (the <script type="module"> block that gen3d.py splices in at
<!--__FURNITURE__-->) from furniture.json + the GLB files in models/.

Each GLB is embedded once as base64 (the page runs from file://, so fetch() is blocked) and
parsed with GLTFLoader + DRACOLoader. Before embedding, the model's bounding box is read from
the glTF accessors and compared with the product-page dimensions; the model is scaled only when
it is off by more than TOL.

Usage:  python3 build_furniture.py            (writes furniture.html next to this file)
"""
import base64, json, struct, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOL = 0.08                      # accept +-8 % (handles, mouldings, rounded cushions)
DRACO = 'https://cdn.jsdelivr.net/npm/three@0.183.0/examples/jsm/libs/draco/gltf/'


def glb_bbox(path):
    """Axis-aligned bbox (x, y, z sizes, metres) from POSITION accessor min/max + node translations."""
    b = path.read_bytes()
    n = struct.unpack('<I', b[12:16])[0]
    j = json.loads(b[20:20 + n])
    lo, hi = [1e9] * 3, [-1e9] * 3
    for node in j.get('nodes', []):
        if 'mesh' not in node:
            continue
        t = node.get('translation', [0, 0, 0])
        for prim in j['meshes'][node['mesh']]['primitives']:
            a = j['accessors'][prim['attributes']['POSITION']]
            lo = [min(l, m + o) for l, m, o in zip(lo, a['min'], t)]
            hi = [max(h, m + o) for h, m, o in zip(hi, a['max'], t)]
    return [h - l for l, h in zip(lo, hi)]


def main():
    spec = json.loads((HERE / 'furniture.json').read_text())
    pieces, models, ok = [], {}, True
    for p in spec['pieces']:
        keep = {k: p[k] for k in ('id', 'product', 'rot_deg', 'x', 'y', 'parent', 'local', 'kind', 'dims_mm', 'colors') if k in p}
        if 'model' not in p:                              # parametric (e.g. bedding): nothing to check
            pieces.append(keep)
            continue
        path = HERE / 'models' / p['model']
        sx, sy, sz = glb_bbox(path)                       # glTF: x = width, y = height, z = depth
        d = p['dims_mm']
        ratios = [sx / (d['w'] / 1000), sz / (d['d'] / 1000), sy / (d['h'] / 1000)]
        bad = any(abs(r - 1) > TOL for r in ratios)
        scale = 1.0
        if bad:                                           # uniform scale by the median ratio
            scale = 1 / sorted(ratios)[1]
            ok = False
        print(f"{p['id']:18s} model {sx:.3f} x {sz:.3f} x {sy:.3f} m  vs page "
              f"{d['w']/1000:.3f} x {d['d']/1000:.3f} x {d['h']/1000:.3f}  "
              f"ratios {', '.join(f'{r:.2f}' for r in ratios)}  scale {scale:.3f}", file=sys.stderr)
        if p['model'] not in models:
            models[p['model']] = base64.b64encode(path.read_bytes()).decode('ascii')
        pieces.append(keep | {'model': p['model'], 'scale': scale})

    js_models = ',\n'.join(f'  {json.dumps(k)}: "{v}"' for k, v in models.items())
    html = f"""<!-- furniture: generated by 3d/furniture/bedroom3/build_furniture.py from furniture.json, do not edit -->
<script type="module">
import {{ GLTFLoader }} from 'three/addons/loaders/GLTFLoader.js';
import {{ DRACOLoader }} from 'three/addons/loaders/DRACOLoader.js';
import {{ RoundedBoxGeometry }} from 'three/addons/geometries/RoundedBoxGeometry.js';
const PIECES = {json.dumps(pieces, ensure_ascii=False)};
const MODELS = {{
{js_models}
}};
while (!window.__ready) await new Promise(r => setTimeout(r, 50));
const {{ THREE, W, group }} = window.__app;
const draco = new DRACOLoader().setDecoderPath('{DRACO}');
const loader = new GLTFLoader().setDRACOLoader(draco);
const buf = b64 => Uint8Array.from(atob(b64), c => c.charCodeAt(0)).buffer;
const parsed = {{}};
for (const [name, b64] of Object.entries(MODELS))
  parsed[name] = await new Promise((res, rej) => loader.parse(buf(b64), '', res, rej));
// the IKEA materials are metallic where there is a mirror/chrome; with no environment map those
// surfaces render black, so give the furniture (only) a plain room-coloured cube map to reflect
const face = hex => {{ const c = document.createElement('canvas'); c.width = c.height = 16;
  const g = c.getContext('2d'); g.fillStyle = hex; g.fillRect(0, 0, 16, 16); return c; }};
const env = new THREE.CubeTexture(['#e9e6dc', '#e9e6dc', '#ffffff', '#b8916a', '#e2e0d6', '#dcdad0'].map(face));
env.colorSpace = THREE.SRGBColorSpace; env.needsUpdate = true;
// parametric pieces without an IKEA model; built in the parent's frame, bottom at y = 0, centred on x/z
const fabric = c => new THREE.MeshStandardMaterial({{ color: c, roughness: 1 }});
const PARAMETRIC = {{
  bedding(p) {{                                       // duvet + 2 pillows on a mattress of dims_mm (w x d)
    const w = p.dims_mm.w / 1000, d = p.dims_mm.d / 1000, g = new THREE.Group();
    const duvet = new THREE.Mesh(new RoundedBoxGeometry(w + 0.06, 0.07, d * 0.74, 4, 0.03), fabric(p.colors?.duvet ?? 0xaebcc6));
    duvet.position.set(0, 0.035, d / 2 - d * 0.37 + 0.02);           // from the foot (+z) to ~0.5 m off the head
    g.add(duvet);
    const fold = new THREE.Mesh(new RoundedBoxGeometry(w + 0.07, 0.09, 0.22, 4, 0.04), fabric(p.colors?.fold ?? 0xf4f1ea));
    fold.position.set(0, 0.045, d / 2 - d * 0.74 + 0.13);            // turned-down top edge of the duvet
    g.add(fold);
    for (const s of [-1, 1]) {{
      const pil = new THREE.Mesh(new RoundedBoxGeometry(0.62, 0.13, 0.44, 5, 0.06), fabric(p.colors?.pillow ?? 0xfbfaf7));
      pil.position.set(s * (w / 4 + 0.005), 0.075, -d / 2 + 0.27);
      pil.rotation.x = -0.25;                                          // leaning back against the headboard
      g.add(pil);
    }}
    return g;
  }},
}};
const furniture = new THREE.Group(); furniture.name = 'furniture-bedroom3';
const byId = {{}};
for (const p of PIECES) {{
  let model;
  if (p.kind) model = PARAMETRIC[p.kind](p);
  else {{
    model = parsed[p.model].scene.clone(true);
    model.scale.setScalar(p.scale);
  }}
  model.traverse(o => {{ if (o.isMesh) {{ o.castShadow = true; o.receiveShadow = true;
    for (const m of [].concat(o.material)) {{ m.envMap = env; m.envMapIntensity = 0.3; m.needsUpdate = true; }} }} }});
  if (!p.kind) {{                                      // parametric pieces are already built centred
    const box = new THREE.Box3().setFromObject(model);
    const c = box.getCenter(new THREE.Vector3());
    model.position.set(-c.x, -box.min.y, -c.z);      // footprint centre at the pivot, bottom on the floor
  }}
  const pivot = new THREE.Group(); pivot.name = p.id;
  pivot.add(model);
  pivot.rotation.y = p.rot_deg * Math.PI / 180;      // world rotation.y = plan angle (CCW); relative if stacked
  if (p.parent) {{ pivot.position.fromArray(p.local); byId[p.parent].add(pivot); }}
  else {{ pivot.position.copy(W(p.x, p.y, 0)); furniture.add(pivot); }}
  byId[p.id] = pivot;
}}
group.add(furniture);
draco.dispose();
window.__furnitureBedroom3 = furniture;
window.__furnitureBedroom3Ready = true;
</script>
"""
    out = HERE / 'furniture.html'
    out.write_text(html)
    print(f'wrote {out} ({out.stat().st_size / 1e6:.2f} MB), {len(pieces)} pieces, {len(models)} models'
          + ('' if ok else '  (some models were rescaled)'), file=sys.stderr)


if __name__ == '__main__':
    main()
