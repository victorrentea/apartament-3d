#!/usr/bin/env python3
"""Regenerate furniture.html (the <script type="module"> block that gen3d.py splices in at
<!--__FURNITURE__-->) from furniture.json + the GLB files in models/.

Each GLB is embedded once as base64 (the page runs from file://, so fetch() is blocked) and
parsed with GLTFLoader + DRACOLoader. Before embedding, the model's bounding box is read from
the glTF accessors and compared with the product-page dimensions; the model is scaled only when
it is off by more than TOL.

Usage:  python3 build_furniture.py            (writes furniture.html next to this file)
"""
import base64, json, struct, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOL = 0.08                      # accept +-8 % (handles, mouldings, rounded cushions)
DRACO = 'https://cdn.jsdelivr.net/npm/three@0.183.0/examples/jsm/libs/draco/gltf/'


def glb_bbox(path):
    """Axis-aligned bbox (x, y, z sizes, metres) from POSITION accessor min/max + node translations."""
    b = path.read_bytes()
    n = struct.unpack('<I', b[12:16])[0]
    j = json.loads(b[20:20 + n])
    lo, hi = [1e9] * 3, [-1e9] * 3
    for node in j.get('nodes', []):
        if 'mesh' not in node:
            continue
        t = node.get('translation', [0, 0, 0])
        for prim in j['meshes'][node['mesh']]['primitives']:
            a = j['accessors'][prim['attributes']['POSITION']]
            lo = [min(l, m + o) for l, m, o in zip(lo, a['min'], t)]
            hi = [max(h, m + o) for h, m, o in zip(hi, a['max'], t)]
    return [h - l for l, h in zip(lo, hi)]


def main():
    spec = json.loads((HERE / 'furniture.json').read_text())
    pieces, models, ok = [], {}, True
    for p in spec['pieces']:
        keep = {k: p[k] for k in ('id', 'product', 'rot_deg', 'tilt_deg', 'x', 'y', 'lift_m', 'parent', 'local', 'kind', 'dims_mm', 'books', 'reskin') if k in p}
        if 'model' not in p:                              # parametric (e.g. bedding): nothing to check
            pieces.append(keep)
            continue
        path = HERE / 'models' / p['model']
        sx, sy, sz = glb_bbox(path)                       # glTF: x = width, y = height, z = depth
        if abs(p.get('tilt_deg', 0)) == 90:               # wall pieces modelled lying flat: y <-> z
            sy, sz = sz, sy
        d = p['dims_mm']                                  # a missing dimension (not on the page) is skipped
        ratios = [m / (d[k] / 1000) if d.get(k) else 1.0 for m, k in ((sx, 'w'), (sz, 'd'), (sy, 'h'))]
        bad = any(abs(r - 1) > TOL for r in ratios)
        scale = 1.0
        if bad:                                           # uniform scale by the median ratio
            scale = 1 / sorted(ratios)[1]
            ok = False
        print(f"{p['id']:18s} model {sx:.3f} x {sz:.3f} x {sy:.3f} m  vs page "
              f"{' x '.join(f'{d[k]/1000:.3f}' if d.get(k) else '?' for k in 'wdh')}  "
              f"ratios {', '.join(f'{r:.2f}' for r in ratios)}  scale {scale:.3f}", file=sys.stderr)
        if p['model'] not in models:
            models[p['model']] = base64.b64encode(path.read_bytes()).decode('ascii')
        pieces.append(keep | {'model': p['model'], 'scale': scale})

    js_models = ',\n'.join(f'  {json.dumps(k)}: "{v}"' for k, v in models.items())
    html = f"""<!-- furniture: generated by 3d/furniture/build_furniture.py from furniture.json, do not edit -->
<script type="module">
import {{ GLTFLoader }} from 'three/addons/loaders/GLTFLoader.js';
import {{ DRACOLoader }} from 'three/addons/loaders/DRACOLoader.js';
import {{ RoundedBoxGeometry }} from 'three/addons/geometries/RoundedBoxGeometry.js';
const PIECES = {json.dumps(pieces, ensure_ascii=False)};
const MODELS = {{
{js_models}
}};
while (!window.__ready) await new Promise(r => setTimeout(r, 50));
const {{ THREE, W, scene }} = window.__app;
const draco = new DRACOLoader().setDecoderPath('{DRACO}');
const loader = new GLTFLoader().setDRACOLoader(draco);
const buf = b64 => Uint8Array.from(atob(b64), c => c.charCodeAt(0)).buffer;
const parsed = {{}};
for (const [name, b64] of Object.entries(MODELS))
  parsed[name] = await new Promise((res, rej) => loader.parse(buf(b64), '', res, rej));
// the IKEA materials are metallic where there is a mirror/chrome; with no environment map those
// surfaces render black, so give the furniture (only) a plain room-coloured cube map to reflect
const face = hex => {{ const c = document.createElement('canvas'); c.width = c.height = 16;
  const g = c.getContext('2d'); g.fillStyle = hex; g.fillRect(0, 0, 16, 16); return c; }};
const env = new THREE.CubeTexture(['#e9e6dc', '#e9e6dc', '#ffffff', '#b8916a', '#e2e0d6', '#dcdad0'].map(face));
env.colorSpace = THREE.SRGBColorSpace; env.needsUpdate = true;
// a brighter cube with gradients (ceiling, walls, window, floor) for real mirror panels, so they read as glass
const grad = (stops, rect) => {{ const c = document.createElement('canvas'); c.width = c.height = 64; const g = c.getContext('2d');
  const lg = g.createLinearGradient(0, 0, 0, 64); for (const [t, col] of stops) lg.addColorStop(t, col);
  g.fillStyle = lg; g.fillRect(0, 0, 64, 64); if (rect) {{ g.fillStyle = rect[4]; g.fillRect(rect[0], rect[1], rect[2], rect[3]); }} return c; }};
const WALL = [[0, '#f6f5f0'], [0.45, '#dcdccb'], [0.62, '#c9c8b4'], [0.66, '#b58a5c'], [1, '#9c7148']];
const mirrorEnv = new THREE.CubeTexture([
  grad(WALL), grad(WALL, [14, 12, 36, 24, '#bcd7ee']),          // +x, -x (window on the west wall)
  grad([[0, '#ffffff'], [1, '#f1efe8']]), grad([[0, '#b88c5f'], [1, '#a77d52']]),
  grad(WALL), grad(WALL, [10, 30, 44, 12, '#f4f1ea'])]);         // +z, -z (white bed/headboard band)
mirrorEnv.colorSpace = THREE.SRGBColorSpace; mirrorEnv.needsUpdate = true;
const mirrorMat = new THREE.MeshStandardMaterial({{ color: 0xdfe7ee, metalness: 1, roughness: 0.05, envMap: mirrorEnv, envMapIntensity: 1,
  polygonOffset: true, polygonOffsetFactor: -2, polygonOffsetUnits: -2 }});
// re-skin a model's door panels (furniture.json "reskin"): rectangles in the model's centred frame, on the panel plane z
function reskin(pivot, rs) {{
  let body; pivot.traverse(o => {{ if (o.isMesh && o.name === rs.mesh) body = o; }});
  const z = rs.z + 0.002;
  for (const pl of rs.plain || []) {{                // cover a panel with a plain one: same texture, UVs of a plain panel
    const [x0, y0, x1, y1] = pl.rect, g = new THREE.PlaneGeometry(x1 - x0, y1 - y0);
    const [bl, br, tl, tr] = pl.uv; g.setAttribute('uv', new THREE.Float32BufferAttribute([...tl, ...tr, ...bl, ...br], 2));
    const m = body.material.clone(); Object.assign(m, {{ polygonOffset: true, polygonOffsetFactor: -2, polygonOffsetUnits: -2 }});
    const mesh = new THREE.Mesh(g, m); mesh.position.set((x0 + x1) / 2, (y0 + y1) / 2, z); mesh.receiveShadow = true; pivot.add(mesh);
  }}
  for (const mr of rs.mirror || []) {{
    const [x0, y0, x1, y1] = mr.rect;
    const mesh = new THREE.Mesh(new THREE.PlaneGeometry(x1 - x0, y1 - y0), mirrorMat);
    mesh.position.set((x0 + x1) / 2, (y0 + y1) / 2, z); mesh.name = 'mirror'; pivot.add(mesh);
  }}
}}
// parametric pieces without an IKEA model; built in the parent's frame, bottom at y = 0, centred on x/z
const fabric = c => new THREE.MeshStandardMaterial({{ color: c, roughness: 1 }});
const PARAMETRIC = {{
  bedding(p) {{                                       // duvet + 2 pillows on a mattress of dims_mm (w x d)
    const w = p.dims_mm.w / 1000, d = p.dims_mm.d / 1000, g = new THREE.Group();
    const duvet = new THREE.Mesh(new RoundedBoxGeometry(w + 0.06, 0.07, d * 0.74, 4, 0.03), fabric(0xaebcc6));
    duvet.position.set(0, 0.035, d / 2 - d * 0.37 + 0.02);           // from the foot (+z) to ~0.5 m off the head
    g.add(duvet);
    const fold = new THREE.Mesh(new RoundedBoxGeometry(w + 0.07, 0.09, 0.22, 4, 0.04), fabric(0xf4f1ea));
    fold.position.set(0, 0.045, d / 2 - d * 0.74 + 0.13);            // turned-down top edge of the duvet
    g.add(fold);
    for (const s of [-1, 1]) {{
      const pil = new THREE.Mesh(new RoundedBoxGeometry(0.62, 0.13, 0.44, 5, 0.06), fabric(0xfbfaf7));
      pil.position.set(s * (w / 4 + 0.005), 0.075, -d / 2 + 0.27);
      pil.rotation.x = -0.25;                                          // leaning back against the headboard
      g.add(pil);
    }}
    return g;
  }},
  books(p) {{                                         // a row of books standing on a shelf, a couple leaning
    const g = new THREE.Group(), cfg = p.books, len = cfg.length_m, depth = cfg.depth_m;
    let seed = cfg.seed || 7;
    const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
    const COLORS = [0x8c2f2a, 0x2f4f6f, 0x3d6b4f, 0xc9a227, 0x5b3a6e, 0xd8d2c4, 0x1f2a36, 0xb5653a, 0x6f8fa6, 0x9a8f7a, 0x2c2c2c, 0xa33b55];
    let x = -len / 2 + 0.02;
    for (let i = 0; i < cfg.count && x < len / 2 - 0.05; i++) {{
      const t = 0.018 + rnd() * 0.035, h = 0.17 + rnd() * 0.11, dd = Math.min(depth - 0.02, 0.12 + rnd() * 0.07);
      const lean = cfg.lean.includes(i);
      const mat = new THREE.MeshStandardMaterial({{ color: COLORS[Math.floor(rnd() * COLORS.length)], roughness: 0.75 }});
      const b = new THREE.Mesh(new THREE.BoxGeometry(t, h, dd), mat);
      if (lean) {{                                   // tipped over sideways, resting on the previous book
        const a = 0.35;
        b.rotation.z = -a;
        b.position.set(x + Math.sin(a) * h / 2 + Math.cos(a) * t / 2, Math.cos(a) * h / 2 + Math.sin(a) * t / 2 - 0.005, 0);
        x += Math.sin(a) * h + t + 0.01;
      }} else {{
        b.position.set(x + t / 2, h / 2, 0);
        x += t + 0.002;
      }}
      g.add(b);
    }}
    return g;
  }},
}};
const furniture = new THREE.Group(); furniture.name = 'furniture';
const byId = {{}};
for (const p of PIECES) {{
  let model;
  if (p.kind) model = PARAMETRIC[p.kind](p);
  else {{
    model = parsed[p.model].scene.clone(true);
    model.scale.setScalar(p.scale);
    if (p.tilt_deg) model.rotation.x = p.tilt_deg * Math.PI / 180;   // wall pieces modelled lying flat
  }}
  model.traverse(o => {{ if (o.isMesh) {{ o.castShadow = true; o.receiveShadow = true;
    for (const m of [].concat(o.material)) {{ m.envMap = env; m.envMapIntensity = 0.3; m.needsUpdate = true; }} }} }});
  if (!p.kind) {{                                      // parametric pieces are already built centred
    const box = new THREE.Box3().setFromObject(model);
    const c = box.getCenter(new THREE.Vector3());
    model.position.set(-c.x, -box.min.y, -c.z);      // footprint centre at the pivot, bottom on the floor
  }}
  const pivot = new THREE.Group(); pivot.name = p.id;
  pivot.add(model);
  pivot.rotation.y = p.rot_deg * Math.PI / 180;      // world rotation.y = plan angle (CCW); relative if stacked
  if (p.parent) {{ pivot.position.fromArray(p.local); byId[p.parent].add(pivot); }}
  else {{ pivot.position.copy(W(p.x, p.y, p.lift_m || 0)); furniture.add(pivot); }}
  if (p.reskin) reskin(pivot, p.reskin);
  byId[p.id] = pivot;
}}
scene.add(furniture);
draco.dispose();
window.__furniture = furniture;
window.__furnitureReady = true;
</script>
"""
    out = HERE / 'furniture.html'
    out.write_text(html)
    print(f'wrote {out} ({out.stat().st_size / 1e6:.2f} MB), {len(pieces)} pieces, {len(models)} models'
          + ('' if ok else '  (some models were rescaled)'), file=sys.stderr)


if __name__ == '__main__':
    main()
