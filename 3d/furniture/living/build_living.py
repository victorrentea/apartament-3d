#!/usr/bin/env python3
"""Regenerate furniture.html for the LIVING ROOM (room 1): the <script type="module"> block that
gen3d.py splices in at <!--__FURNITURE__--> (it globs 3d/furniture/*/furniture.html).

Reads furniture.json + the IKEA GLBs in models/ (private use only, never publish) and the page code
in living.js. Each GLB is embedded once as base64 (the page runs from file://, so fetch() is blocked)
and parsed with GLTFLoader + DRACOLoader. The model bbox (glTF accessors) is compared with the
product-page dimensions; a model is rescaled only when it is off by more than TOL.
Pieces with "kind" (tv, bike) are drawn from code in living.js; "books" fills a bookcase's shelves.

Usage:  python3 build_living.py
"""
import base64, json, struct, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOL = 0.08
DRACO = 'https://cdn.jsdelivr.net/npm/three@0.183.0/examples/jsm/libs/draco/gltf/'
MAX_BYTES = 6_000_000


def glb_bbox(path):
    """Axis-aligned bbox sizes (x, y, z metres) from POSITION accessor min/max + node translations."""
    b = path.read_bytes()
    n = struct.unpack('<I', b[12:16])[0]
    j = json.loads(b[20:20 + n])
    lo, hi = [1e9] * 3, [-1e9] * 3
    for node in j.get('nodes', []):
        if 'mesh' not in node:
            continue
        t = node.get('translation', [0, 0, 0])
        for prim in j['meshes'][node['mesh']]['primitives']:
            a = j['accessors'][prim['attributes']['POSITION']]
            lo = [min(l, m + o) for l, m, o in zip(lo, a['min'], t)]
            hi = [max(h, m + o) for h, m, o in zip(hi, a['max'], t)]
    return [h - l for l, h in zip(lo, hi)]


def main():
    spec = json.loads((HERE / 'furniture.json').read_text())
    pieces, models = [], {}
    for p in spec['pieces']:
        if p.get('kind'):                                 # drawn from code in the page (no 3D model available)
            pieces.append({k: p[k] for k in ('id', 'product', 'kind', 'x', 'y', 'h', 'rot_deg', 'dims_mm') if k in p})
            print(f"{p['id']:13s} drawn from code ({p['kind']})", file=sys.stderr)
            continue
        path = HERE / 'models' / p['model']
        sx, sy, sz = glb_bbox(path)                       # glTF: x = width, y = height, z = depth
        wall = p.get('orient') == 'wall'
        if wall:                                          # IKEA pictures lie flat: y = thickness, z = picture height
            sy, sz = sz, sy
        d = p['dims_mm']
        ratios = [sx / (d['w'] / 1000), sz / (d['d'] / 1000), sy / (d['h'] / 1000)]
        scale = 1 / sorted(ratios)[1] if any(abs(r - 1) > TOL for r in ratios) else 1.0
        print(f"{p['id']:13s} model {sx:.3f} x {sz:.3f} x {sy:.3f} m  vs page "
              f"{d['w']/1000:.3f} x {d['d']/1000:.3f} x {d['h']/1000:.3f}  "
              f"ratios {', '.join(f'{r:.2f}' for r in ratios)}  scale {scale:.3f}", file=sys.stderr)
        models.setdefault(p['model'], base64.b64encode(path.read_bytes()).decode('ascii'))
        pieces.append({k: p[k] for k in ('id', 'product', 'model', 'x', 'y', 'rot_deg')} | {'scale': scale}
                      | ({'wall': True, 'h': p['h'], 'flip': p.get('flip', 1)} if wall else {})
                      | ({'books': p['books']} if 'books' in p else {}))

    js_models = '{\n' + ',\n'.join(f'  {json.dumps(k)}: "{v}"' for k, v in models.items()) + '\n}'
    js = (HERE / 'living.js').read_text()
    js = (js.replace('__PIECES__', json.dumps(pieces, ensure_ascii=False))
            .replace('__MODELS__', js_models).replace('__DRACO__', DRACO))
    html = ('<!-- living-room furniture: generated by 3d/furniture/living/build_living.py from furniture.json'
            ' + living.js, do not edit -->\n<script type="module">\n' + js + '</script>\n')
    out = HERE / 'furniture.html'
    out.write_text(html)
    size = out.stat().st_size
    print(f'wrote {out} ({size / 1e6:.2f} MB), {len(pieces)} pieces, {len(models)} models', file=sys.stderr)
    if size > MAX_BYTES:
        sys.exit(f'furniture.html is over {MAX_BYTES / 1e6:.0f} MB')


if __name__ == '__main__':
    main()
